def bid(sid):     # blueprint id
    return sid.lower()


def runs(row):
    d = np.diff(np.concatenate([[0], row.astype(np.int8), [0]]))
    return list(zip(np.nonzero(d == 1)[0], np.nonzero(d == -1)[0] - 1))


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    best, idx = -1, 0
    for i in range(1, len(pts) - 1):
        t = (pts[i][0] - a[0]) / (b[0] - a[0])
        d = abs(pts[i][1] - (a[1] + t * (b[1] - a[1])))
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [a, b]
    return dp(pts[:idx + 1], tol)[:-1] + dp(pts[idx:], tol)


SMOOTH_ROWS = 1.0   # Gaussian sigma along the blade, in sheet rows (takes the pixel stairs off; notches stay crisp)


def smooth_rows(pts, cut=None):
    """Gaussian along the blade (rows), ends held; with `cut` (a u), each side of it on its own (a fork's step)."""
    if cut is not None:
        return smooth_rows([p for p in pts if p[0] <= cut]) + smooth_rows([p for p in pts if p[0] > cut])
    v = np.array([p[1] for p in pts])
    r = int(3 * SMOOTH_ROWS)
    w = np.exp(-0.5 * (np.arange(-r, r + 1) / SMOOTH_ROWS) ** 2); w /= w.sum()
    sm = np.convolve(np.pad(v, r, mode='edge'), w, 'valid')
    sm[0], sm[-1] = v[0], v[-1]
    return [(p[0], float(x)) for p, x in zip(pts, sm)]


def sheet_dark(sid):
    """The sword's crop of its sheet as darkness 0..1 (anti-aliased), for sub-pixel edges."""
    cells = json.load(open(os.path.join(HERE, 'cells.json')))
    c = cells[sid]
    g = cv2.imread(os.path.join(HERE, '..', '..', '..', 'References', 'Sword Silhouettes', c['sheet']), 0)
    return 1 - g[c['y0']:c['y0'] + c['h'], c['x0']:c['x0'] + c['w']].astype(np.float32) / 255.0


def sub_edges(d, y, l, r):
    """Sub-pixel left and right edges of the run l..r on row y (index coords: a pixel's centre is its index),
    where the darkness crosses 0.5; the run's pixel bounds where the grey doesn't help."""
    W = d.shape[1]
    xl, xr = l - 0.5, r + 0.5
    if l > 0 and d[y, l] > d[y, l - 1]:
        xl = (l - 1) + float(np.clip((0.5 - d[y, l - 1]) / (d[y, l] - d[y, l - 1]), 0, 1))
    if r < W - 1 and d[y, r] > d[y, r + 1]:
        xr = r + float(np.clip((d[y, r] - 0.5) / (d[y, r] - d[y, r + 1]), 0, 1))
    return xl, xr


def trace(sid, mt):
    dark = sheet_dark(sid)
    lab = cv2.imread(os.path.join(HERE, 'parts', sid + '.png'), 0)
    B = (lab == 1).astype(np.uint8)
    be, gt, gb = mt['cuts']
    axis = mt['axis']
    # the base runs on into the guard (SEAT rows across the bottom row's full width), so a hole cut by the blade/guard
    # line (Eclipse Fang's moon) is closed and counts
    xs = np.nonzero(B[be - 1])[0]
    B[be:be + SEAT + 1, xs.min():xs.max() + 1] = 1
    # fill holes; keep the biggest real one
    cs, hier = cv2.findContours(B, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    F = B.copy()
    hole = None
    best = 0
    for i, c in enumerate(cs):
        if hier[0][i][3] >= 0:          # a hole
            cv2.drawContours(F, [c], -1, 1, -1)
            x, y, w, h = cv2.boundingRect(c)
            area = cv2.contourArea(c)
            if sid in HOLES and area >= 30 and min(w, h) >= 3 and area > best:
                best, hole = area, c
    H = np.zeros_like(B)
    if hole is not None:
        cv2.drawContours(H, [hole], -1, 1, -1)
        H &= (1 - B)
    rows = np.nonzero(F.any(1))[0]
    top = int(rows.min())
    spans = {}
    fork = {}       # row -> (left prong run, right prong run)
    prev = None
    for y in range(be - 1, top - 1, -1):
        rs = runs(F[y])
        if not rs:
            break
        if sid in FORK and len(rs) > 1:
            pick = (rs[0][0], rs[-1][1])
            fork[y] = (rs[0], rs[-1])
        elif prev is None:
            pick = min(rs, key=lambda r: 0 if r[0] <= axis <= r[1] else min(abs(r[0] - axis), abs(r[1] - axis)))
        else:
            def ov(r):
                return min(r[1], prev[1]) - max(r[0], prev[0])
            pick = max(rs, key=ov)
            if ov(pick) < 0:      # nothing overlaps: the nearest
                pick = min(rs, key=lambda r: abs((r[0] + r[1]) / 2 - (prev[0] + prev[1]) / 2))
        spans[y] = pick
        prev = pick
    tip = min(spans)
    for y in range(be, be + SEAT + 1):
        spans[y] = spans[be - 1]
    base = be + SEAT
    L = (base - tip + 1) * CM
    # the fork's top row: the shorter prong ends there, drawn to zero width on its own centre line (so nothing bridges
    # the V on the way to the longer prong's side); `ends` is the blade side it's on
    ftop = min(fork) if fork else None
    ends = None
    if ftop is not None:
        lr, rr = fork[ftop]
        above = spans[ftop - 1]
        ends = 'spine' if min(above[1], lr[1]) - max(above[0], lr[0]) >= 0 else 'edge'   # the left prong goes on: the right one ends
    sp, ed, holes, gaps = [], [], [], []
    for y in sorted(spans):
        l, r = spans[y]
        u = (base - y) / (base - tip)
        xl, xr = sub_edges(dark, min(y, be - 1), l, r)
        if y == ftop:
            lr, rr = fork[y]
            if ends == 'spine':
                xr = (rr[0] + rr[1]) / 2
            else:
                xl = (lr[0] + lr[1]) / 2
        s, e = (xr - axis) * CM, (xl - axis) * CM
        sp.append((u, s)); ed.append((u, e))
        if y in fork:
            lr, rr = fork[y]
            w = s - e
            a = (s - (rr[0] - 0.5 - axis) * CM) / w
            b = (s - (lr[1] + 0.5 - axis) * CM) / w
            if y == ftop:
                a, b = (0.0, b) if ends == 'spine' else (a, 1.0)
            gaps.append((u, a, b))
        elif H[y].any():
            g = [c for c in range(l, r + 1) if H[y, c]]
            if g:
                w = s - e
                a = (s - (max(g) + 0.5 - axis) * CM) / w
                b = (s - (min(g) - 0.5 - axis) * CM) / w
                holes.append((u, max(0.06, a), min(0.94, b)))
    sp.sort(); ed.sort()
    sp[0] = (0.0, sp[0][1]); ed[0] = (0.0, ed[0][1]); sp[-1] = (1.0, sp[-1][1]); ed[-1] = (1.0, ed[-1][1])
    cut = (base - ftop) / (base - tip) if ftop is not None else None
    sp, ed = smooth_rows(sp, cut), smooth_rows(ed, cut)
    du = 1.0 / (base - tip)

    def closed(pts, last=None, double=False):
        """Every third point and the last, closed (a == b) one row before and after. `double`: each closing point twice,
        so the curves leave it flat and the sides stay together until the next opening (the bridge under a fork)."""
        hs = pts[::3]
        if hs[-1] != pts[-1]:
            hs.append(pts[-1])
        c0 = (hs[0][1] + hs[0][2]) / 2
        c1 = last if last is not None else (hs[-1][1] + hs[-1][2]) / 2
        u0, u1 = max(0.0, hs[0][0] - du), min(1.0, hs[-1][0] + du)
        if not double:
            return [(u0, c0, c0)] + hs + [(u1, c1, c1)]
        return [(max(0.0, u0 - du), c0, c0), (u0, c0, c0)] + hs + [(u1, c1, c1), (min(1.0, u1 + du), c1, c1)]

    hole_pts = None
    if holes or gaps:
        hole_pts = []
        if holes:
            hole_pts += closed(sorted(holes), double=bool(gaps))
        if gaps:
            hole_pts += closed(sorted(gaps), last=0.0 if ends == 'spine' else 1.0, double=True)
        hole_pts.sort()
        hole_pts = [(round(u, 4), round(a, 4), round(max(a, b), 4)) for u, a, b in hole_pts]
        # a doubled closing point clamped to the tip (a fork's) lands on the same u: keep the first (curves need rising u)
        hole_pts = [p for k, p in enumerate(hole_pts) if k == 0 or p[0] > hole_pts[k - 1][0]]
    return dict(L=L, spine=[(round(u, 4), round(v, 4)) for u, v in dp(sp, TOL)],
                edge=[(round(u, 4), round(v, 4)) for u, v in dp(ed, TOL)], hole=hole_pts, fork=bool(gaps),
                rows=(tip, base), spans=spans)


def make_curve(points):
    n = len(points); xs = [p[0] for p in points]; ys = [p[1] for p in points]
    if n == 1:
        return lambda u: ys[0]
    d = [(ys[k + 1] - ys[k]) / (xs[k + 1] - xs[k]) for k in range(n - 1)]
    m = [0.0] * n; m[0], m[-1] = d[0], d[-1]
    for k in range(1, n - 1):
        m[k] = 0 if d[k - 1] * d[k] <= 0 else (d[k - 1] + d[k]) / 2
    for k in range(n - 1):
        if d[k] == 0:
            m[k] = m[k + 1] = 0
        else:
            a, b = m[k] / d[k], m[k + 1] / d[k]; s = a * a + b * b
            if s > 9:
                t = 3 / math.sqrt(s); m[k], m[k + 1] = t * a * d[k], t * b * d[k]
    def f(u):
        if u <= xs[0]: return ys[0]
        if u >= xs[-1]: return ys[-1]
        k = 0
        while u > xs[k + 1]: k += 1
        h = xs[k + 1] - xs[k]; t = (u - xs[k]) / h; t2, t3 = t * t, t * t * t
        return (2*t3 - 3*t2 + 1) * ys[k] + (t3 - 2*t2 + t) * h * m[k] + (-2*t3 + 3*t2) * ys[k + 1] + (t3 - t2) * h * m[k + 1]
    return f


def fmt(x):
    s = ("%.3f" % x).rstrip("0").rstrip(".")
    s = "0" if s in ("-0", "") else s
    return s.replace("0.", ".", 1) if s.startswith("0.") else s.replace("-0.", "-.", 1)


def pts(p):
    """Flat and compact: P{u, v, u, v, ...} (or T{...} for triples); the module's P / T rebuild the pairs."""
    return ("T" if len(p[0]) == 3 else "P") + "{" + ",".join(fmt(v) for q in p for v in q) + "}"


def shape_lua(sh, ind):
    t = "\t" * ind
    out = (f"{{\n{t}\tlength = {fmt(sh['length'])},\n{t}\tcurve = {{ sori = 0, center = 0.5, spread = 0.35 }},\n"
           f"{t}\tspine = {pts(sh['spine'])},\n{t}\tedge = {pts(sh['edge'])},\n{t}\tridge = {pts(sh['ridge'])},\n"
           f"{t}\tthickness = {pts(sh['thickness'])},\n{t}\tedgeThickness = {pts(sh['edgeThickness'])},\n"
           f"{t}\tspineThickness = {pts(sh['spineThickness'])},\n")
    if sh.get('hole'):
        out += f"{t}\thole = {pts(sh['hole'])},\n"
    if sh.get('fork'):
        out += f"{t}\tfork = true,\n"
    return out + f"{t}}}"


def flipped(tr):
    """The blade turned half a turn about its axis: the edge becomes the spine's mirror and back."""
    return dict(tr, spine=[(u, -v) for u, v in tr['edge']], edge=[(u, -v) for u, v in tr['spine']],
                hole=[(u, round(1 - b, 4), round(1 - a, 4)) for u, a, b in tr['hole']] if tr['hole'] else None)


def stages(sid, tr):
    double = sid not in SINGLE
    L = round(tr['L'], 2)
    refined = dict(length=L, spine=tr['spine'], edge=tr['edge'], ridge=[(0, 0.5 if double else 0.35)],
                   thickness=[(0, 0.9), (0.5, 0.75), (1, 0.35)], edgeThickness=[(0, 0.03)],
                   spineThickness=[(0, 0.06 if double else 0.8)], hole=tr['hole'], fork=tr.get('fork', False))
    S, E = make_curve(tr['spine']), make_curve(tr['edge'])
    us = [i / (N - 1) for i in range(N)]
    mean_w = sum(S(u) - E(u) for u in us) / N
    h = round(min(2.6, max(1.2, 0.5 * mean_w)), 2)
    lengthened = dict(length=round(0.78 * L, 1), spine=[(0, h), (0.92, round(0.95 * h, 4)), (1, round(0.8 * h, 4))],
                      edge=[(0, -h), (0.92, round(-0.95 * h, 4)), (1, round(-0.8 * h, 4))],
                      ridge=[(0, 0.5 if double else 0.85)], thickness=[(0, 0.95), (1, 0.82)],
                      edgeThickness=[(0, 0.55)], spineThickness=[(0, 0.6 if double else 0.92)])
    ps, pe = [], []
    for k in range(11):
        u = k / 10
        win = [x for x in us if abs(x - u) <= 0.05]
        ps.append((u, round(sum(S(x) for x in win) / len(win), 4))); pe.append((u, round(sum(E(x) for x in win) / len(win), 4)))
    for k in range(len(ps)):
        if ps[k][1] - pe[k][1] < 0.3:
            m = (ps[k][1] + pe[k][1]) / 2
            ps[k], pe[k] = (ps[k][0], round(m + 0.15, 4)), (pe[k][0], round(m - 0.15, 4))
    preform = dict(length=L, spine=ps, edge=pe, ridge=[(0, 0.5 if double else 0.4)], thickness=[(0, 0.86), (1, 0.62)],
                   edgeThickness=[(0, 0.28)], spineThickness=[(0, 0.32 if double else 0.85)])
    return lengthened, preform, refined, double


def profile_lua(sid, tr, grip_cm):
    le, pr, re, double = stages(sid, tr)
    rec = ",\n".join(f"\t\t\t\t{{ stage = \"{s}\", u = {fmt(u)}, radius = {fmt(r)}, side = \"{side}\", flip = {str(f).lower()}, turn = {t} }}"
                     for s, u, r, side, f, t in RECIPE)
    note = f"Traced {TRACED.get(sid, '2026-11-10')}; Dev Panel only, not approved." + (" Real hole." if tr['hole'] else "") + (" Open fork at the tip." if tr.get('fork') else "")
    return (f"\t\t{bid(sid)} = {{\n\t\t\tid = \"{bid(sid)}\",\n\t\t\tname = \"{NAMES.get(sid, sid)}\",\n\t\t\tversion = {VERSIONS.get(sid, 1)},\n"
            f"\t\t\tnote = {json.dumps(note, ensure_ascii=False)},\n\t\t\tstations = {N},\n"
            + ("\t\t\tdoubleEdged = true,\n" if double else "")
            + f"\t\t\ttang = {{ length = {fmt(grip_cm)}, width = 1.8 }},\n"
            f"\t\t\tstages = {{\n\t\t\t\tlengthened = {shape_lua(le, 4)},\n\t\t\t\tpreform = {shape_lua(pr, 4)},\n\t\t\t\trefined = {shape_lua(re, 4)},\n\t\t\t}},\n"
            f"\t\t\tforgedAllowance = {{ edge = 0.14, edgeThickness = 0.12 }},\n"
            f"\t\t\trecipe = RECIPE,\n\t\t}},\n")


