"""BladeData profiles and hilt numbers for the 22 new silhouette swords (miniconda python: cv2, numpy).
python profiles.py  ->  NewSilhouetteBlades.luau (Shared.NewSilhouetteBlades: the profiles and their order), hilts.json (GripLength / BladeOffset / Back, studs),
                        profiles_check.png (each traced blade outline over its sheet mask)

The blade is traced from parts/<id>.png (label 1), base to tip, row by row, keeping the run that continues the
blade's body (a thorn's tip standing apart from the blade is left out: a BladeCore blade has one spine and one edge
per station). A real hole (an enclosed gap of 30 px² or more, at least 3 px wide) becomes the profile's `hole`
(BladeCore.HOLE_PARAMS, fractions across from the spine); a smaller one is filled. Single-edged blades put their edge
on the sheet's left (the hilt frame's +Z); the spine is the right. The blade starts SEAT px below its cut row, inside
the guard. Straight centreline (the curves are in the spine/edge offsets). Same 10-strike recipe as the Thornspire.
Units: cm (0.2222 cm per sheet px: a 450 px sword is 5 studs at Blueprints.STUDS_PER_CM 0.05)."""
