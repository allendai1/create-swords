// Converts the blade JSON data into Luau ModuleScripts for Roblox, plus golden values computed by
// the JavaScript core so the Luau port can be checked against it number for number.
// Run: node tools/export-luau.js   (writes roblox/BladeData.luau and roblox/BladeGolden.luau)
import { readFileSync, writeFileSync } from 'fs';
import * as core from '../dist/js/blade-core.js';

const dataUrl = (f) => new URL(`../dist/data/${f}`, import.meta.url);
const load = (f) => JSON.parse(readFileSync(dataUrl(f), 'utf8'));
const out = (f, text) => writeFileSync(new URL(`../roblox/${f}`, import.meta.url), text);

function toLuau(value, indent = '') {
  if (value === null || value === undefined) return 'nil';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`cannot write ${value}`);
    return Object.is(value, -0) ? '0' : String(value);
  }
  if (typeof value === 'boolean') return String(value);
  if (typeof value === 'string') return JSON.stringify(value);
  const inner = indent + '\t';
  if (Array.isArray(value)) {
    if (value.every((v) => typeof v !== 'object' || (Array.isArray(v) && v.every((x) => typeof x !== 'object')))) {
      return `{ ${value.map((v) => toLuau(v, inner)).join(', ')} }`;
    }
    return `{\n${value.map((v) => `${inner}${toLuau(v, inner)},`).join('\n')}\n${indent}}`;
  }
  const entries = Object.entries(value).filter(([, v]) => v !== undefined);
  const key = (k) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`);
  return `{\n${entries.map(([k, v]) => `${inner}${key(k)} = ${toLuau(v, inner)},`).join('\n')}\n${indent}}`;
}

const header = (what) => `--!strict\n-- GENERATED by Prototypes/tanto-forge/tools/export-luau.js from dist/data. Do not edit by hand:\n-- change the JSON (or use the profile editor), then run \`node tools/export-luau.js\`.\n-- ${what}\n`;

const { profiles: index } = load('profiles.json');
const blank = load('blank.json');
const profiles = index.map((e) => load(e.file));

out('BladeData.luau', `${header('Blade profiles for BladeCore.')}
return ${toLuau({ blank, order: profiles.map((p) => p.id), profiles: Object.fromEntries(profiles.map((p) => [p.id, p])) })}
`);

// Golden values: what the JavaScript core computes for each profile.
const round = (v) => Math.round(v * 1e6) / 1e6;
const golden = {};
for (const profile of profiles) {
  const blade = core.createBlade(blank, profile);
  const states = core.forgingStates(blade);
  const sample = (st) => {
    const pos = core.buildPositions(core.stationParams(blade, st));
    let sum = 0;
    for (const v of pos) sum += Math.abs(v);
    // A few individual vertices (1-based vertex numbers, xyz) catch ordering mistakes.
    const pick = [1, 13, 100, 400, 700, core.vertexCount(blade.stations)].map((v) => [v, round(pos[(v - 1) * 3]), round(pos[(v - 1) * 3 + 1]), round(pos[(v - 1) * 3 + 2])]);
    return { absSum: round(sum), vertices: pick };
  };
  let ground = states[states.length - 2];
  ground = core.applyGrind(blade, ground, 0.3, 0.5);
  ground = core.applyGrind(blade, ground, 0.9, 0.25);
  const target = core.strikeTarget(blade, core.stationParams(blade, states[0]), 0);
  const m = core.measureShape(profile.stages.refined, blade.stations);
  golden[profile.id] = {
    vertexCount: core.vertexCount(blade.stations),
    indexCount: core.buildIndex(blade.stations).length,
    length: round(blade.length),
    qualityByStrike: states.slice(0, -1).map((st) => round(core.quality(blade, st))),
    blank: sample(states[0]),
    strike6: sample(states[6]),
    forged: sample(states[states.length - 2]),
    refined: sample(states[states.length - 1]),
    groundQuality: round(core.quality(blade, ground)),
    groundRuns: core.unfinishedRuns(blade, ground).map(([a, b]) => [a + 1, b + 1]),
    firstStrike: { station: target.station + 1, point: target.point.map(round), angle: round(target.angle), thickness: round(target.thickness) },
    measured: { nagasa: round(m.nagasa), sori: round(m.sori) },
  };
}
out('BladeGolden.luau', `${header('Values the JavaScript core computes, for BladeCoreSpec to compare against.')}
return ${toLuau(golden)}
`);
console.log(`Wrote roblox/BladeData.luau (${profiles.map((p) => p.id).join(', ')}) and roblox/BladeGolden.luau`);
